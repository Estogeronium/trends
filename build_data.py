def tagset(tags):
    t = {x.lower().replace("-", " ") for x in tags}
    return sorted(k for k, v in TAGMAP.items() if t & v)

def glyph(cid):
    rnd = random.Random(cid)
    kinds = ["o", "O", "s", "t", "h", "x", "."]
    wts = [3, 1, 3, 2, 2, 1, 2]
    cell = lambda: rnd.choices(kinds, wts)[0]
    out = []
    for _ in range(3):
        a, b = cell(), cell()
        out += [a, b, a]
    if all(c == "." for c in out): out[4] = "O"
    return "".join(out)

