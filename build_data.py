def tagset(tags):
    t = {x.lower().replace("-", " ") for x in tags}
    return sorted(k for k, v in TAGMAP.items() if t & v)

def glyph(cid):
    rnd = random.Random(cid)
    kinds = ["o", "O", "s", "t", "h", "x", "."]
    wts = [3, 1, 3, 2, 2, 1, 2]
    cell = lambda: rnd.choices(kinds, wts)[0]
    out = []
    for _ in range(3):
        a, b = cell(), cell()
        out += [a, b, a]
    if all(c == "." for c in out): out[4] = "O"
    return "".join(out)

trends = []
for r in rows:
    trends.append(dict(
        id=r["id"], c=r["cluster"], t=r["trend_ru"], d=r["thesis_ru"], e=ev.get(r["id"], ""),
        s=r["publisher"], p=r["page"], h=r["horizon"], st=r["stance"], tg=tagset(r["tags"])))

def spread(ts):
    """Внутри паттерна: сначала тренды с данными, источники по кругу, чтобы первые карточки были из разных отчётов."""
    by = collections.OrderedDict()
    for t in sorted(ts, key=lambda t: (t["e"] == "", )):
        by.setdefault(t["s"], []).append(t)
    out = []
    while by:
        for k in list(by):
            out.append(by[k].pop(0))
            if not by[k]: del by[k]
    return out

order = {}
for cid in CL:
    for i, t in enumerate(spread([t for t in trends if t["c"] == cid])): order[t["id"]] = i
trends.sort(key=lambda t: (list(CL).index(t["c"]), order[t["id"]]))

pubs_all = sorted({t["s"] for t in trends})
clusters = []
for n, (cid, (g, name, line, act)) in enumerate(CL.items(), 1):
    ts = [t for t in trends if t["c"] == cid]
    clusters.append(dict(id=cid, n=n, g=g, name=name, glyph=glyph(cid), line=line, act=act,
                         count=len(ts), sources=sorted({t["s"] for t in ts})))
maxsrc = max(len(c["sources"]) for c in clusters)

